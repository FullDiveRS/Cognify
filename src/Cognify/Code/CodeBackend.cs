using System.Text;

namespace Cognify.Code;

/// <summary>
/// What kind of code was requested, guessed from the natural-language intent.
/// </summary>
public enum CodeRequestKind
{
    /// <summary>An ordinary class with fields and a method.</summary>
    Class,
    /// <summary>A single function or method.</summary>
    Function,
    /// <summary>A loop over a collection.</summary>
    Loop,
    /// <summary>A SQL query.</summary>
    Query,
    /// <summary>A REST/HTTP endpoint sketch.</summary>
    Endpoint,
    /// <summary>Anything else — a generic scaffold.</summary>
    Generic
}

/// <summary>A request to generate code.</summary>
/// <param name="Description">What the code should do, in plain language.</param>
/// <param name="Kind">The kind of code to generate.</param>
/// <param name="Language">Target language ("csharp", "python", "javascript", "sql").</param>
/// <param name="Name">Suggested identifier name (may be empty — then derived).</param>
public sealed record CodeRequest(string Description, CodeRequestKind Kind, string Language, string Name = "");

/// <summary>The generated code plus metadata.</summary>
public sealed class CodeResult
{
    /// <summary>The code itself.</summary>
    public string Source { get; internal set; } = string.Empty;

    /// <summary>Language of the generated code.</summary>
    public string Language { get; internal set; } = "csharp";

    /// <summary>Kind of scaffold produced.</summary>
    public CodeRequestKind Kind { get; internal set; }

    /// <summary>Notes about what was generated (todo points, caveats).</summary>
    public IReadOnlyList<string> Notes { get; internal set; } = Array.Empty<string>();
}

/// <summary>
/// Pluggable code-generation backend. Implement this to wire in a real code
/// model (an LLM API); the built-in one emits clean templates.
/// </summary>
public interface ICodeBackend
{
    /// <summary>Generates code for a request.</summary>
    CodeResult Generate(CodeRequest request);
}

/// <summary>
/// Template-based code generation: real, compilable-in-spirit scaffolds for
/// the common intents (class, function, loop, SQL query, endpoint). Every
/// scaffold includes doc comments and a note that it is a starting point.
/// </summary>
public sealed class TemplateCodeBackend : ICodeBackend
{
    /// <inheritdoc />
    public CodeResult Generate(CodeRequest request)
    {
        var name = Identifier(request.Name, request.Description, request.Kind);
        var description = string.IsNullOrWhiteSpace(request.Description) ? "the task" : request.Description.Trim();

        return request.Language.ToLowerInvariant() switch
        {
            "python" => GeneratePython(request with { Name = name }, description),
            "javascript" or "js" or "typescript" or "ts" => GenerateJavaScript(request with { Name = name }, description),
            "sql" => GenerateSql(request with { Name = name }, description),
            _ => GenerateCSharp(request with { Name = name }, description)
        };
    }

    private CodeResult GenerateCSharp(CodeRequest request, string description)
    {
        var sb = new StringBuilder();
        sb.AppendLine($"// Generated by Cognify — {request.Kind} scaffold for: {description}");
        sb.AppendLine("using System;");
        sb.AppendLine();
        sb.AppendLine($"namespace {Namespace ?? "Generated"};");
        sb.AppendLine();

        switch (request.Kind)
        {
            case CodeRequestKind.Function:
                sb.AppendLine($"public static class {request.Name}Extensions");
                sb.AppendLine("{");
                sb.AppendLine("    /// <summary>");
                sb.AppendLine($"    /// {description}");
                sb.AppendLine("    /// </summary>");
                sb.AppendLine($"    public static double {request.Name}(this double[] values)");
                sb.AppendLine("    {");
                sb.AppendLine("        if (values is null || values.Length == 0)");
                sb.AppendLine("            throw new ArgumentException(\"Need at least one value.\", nameof(values));");
                sb.AppendLine();
                sb.AppendLine("        // TODO: implement the actual logic");
                sb.AppendLine("        double sum = 0;");
                sb.AppendLine("        foreach (var v in values) sum += v;");
                sb.AppendLine("        return sum / values.Length;");
                sb.AppendLine("    }");
                sb.AppendLine("}");
                break;

            case CodeRequestKind.Loop:
                sb.AppendLine($"public static class {request.Name}Runner");
                sb.AppendLine("{");
                sb.AppendLine("    /// <summary>Processes every item in the collection.</summary>");
                sb.AppendLine($"    public static void {request.Name}(IEnumerable<string> items)");
                sb.AppendLine("    {");
                sb.AppendLine("        foreach (var item in items)");
                sb.AppendLine("        {");
                sb.AppendLine("            // TODO: process each item");
                sb.AppendLine("            Console.WriteLine(item);");
                sb.AppendLine("        }");
                sb.AppendLine("    }");
                sb.AppendLine("}");
                break;

            case CodeRequestKind.Query:
                goto case CodeRequestKind.Function;

            case CodeRequestKind.Endpoint:
                sb.AppendLine("using Microsoft.AspNetCore.Builder;");
                sb.AppendLine("using Microsoft.AspNetCore.Http;");
                sb.AppendLine();
                sb.AppendLine($"public static class {request.Name}Endpoint");
                sb.AppendLine("{");
                sb.AppendLine("    /// <summary>Maps a minimal HTTP endpoint.</summary>");
                sb.AppendLine("    public static void Map(WebApplication app)");
                sb.AppendLine("    {");
                sb.AppendLine("        app.MapGet(\"/" + request.Name.ToLowerInvariant() + "\", () =>");
                sb.AppendLine("        {");
                sb.AppendLine($"            // TODO: {description}");
                sb.AppendLine("            return Results.Ok(new { status = \"ok\" });");
                sb.AppendLine("        });");
                sb.AppendLine("    }");
                sb.AppendLine("}");
                break;

            case CodeRequestKind.Class:
            default:
                sb.AppendLine("/// <summary>");
                sb.AppendLine($"/// {description}");
                sb.AppendLine("/// </summary>");
                sb.AppendLine($"public sealed class {request.Name}");
                sb.AppendLine("{");
                sb.AppendLine("    /// <summary>Creates a new instance.</summary>");
                sb.AppendLine($"    public {request.Name}() {{ }}");
                sb.AppendLine();
                sb.AppendLine("    // TODO: add fields, properties and behavior");
                sb.AppendLine("}");
                break;
        }

        return new CodeResult
        {
            Source = sb.ToString(),
            Language = "csharp",
            Kind = request.Kind,
            Notes = new[] { "This is a scaffold — replace the TODOs with real logic." }
        };
    }

    private CodeResult GeneratePython(CodeRequest request, string description)
    {
        var sb = new StringBuilder();
        sb.AppendLine($"# Generated by Cognify — {request.Kind} scaffold for: {description}");
        sb.AppendLine();
        if (request.Kind == CodeRequestKind.Class)
        {
            sb.AppendLine($"class {request.Name}:");
            sb.AppendLine($"    \"\"\"{description}\"\"\"");
            sb.AppendLine();
            sb.AppendLine("    def __init__(self) -> None:");
            sb.AppendLine("        # TODO: add state");
            sb.AppendLine("        pass");
        }
        else
        {
            sb.AppendLine($"def {request.Name}(items):");
            sb.AppendLine($"    \"\"\"{description}\"\"\"");
            sb.AppendLine("    # TODO: implement the actual logic");
            sb.AppendLine("    results = []");
            sb.AppendLine("    for item in items:");
            sb.AppendLine("        results.append(item)");
            sb.AppendLine("    return results");
        }
        return new CodeResult
        {
            Source = sb.ToString(),
            Language = "python",
            Kind = request.Kind,
            Notes = new[] { "This is a scaffold — replace the TODOs with real logic." }
        };
    }

    private CodeResult GenerateJavaScript(CodeRequest request, string description)
    {
        var sb = new StringBuilder();
        sb.AppendLine($"// Generated by Cognify — {request.Kind} scaffold for: {description}");
        sb.AppendLine();
        if (request.Kind == CodeRequestKind.Class)
        {
            sb.AppendLine($"class {request.Name} {{");
            sb.AppendLine("  constructor() {");
            sb.AppendLine("    // TODO: add state");
            sb.AppendLine("  }");
            sb.AppendLine("}");
        }
        else
        {
            sb.AppendLine($"/** {description} */");
            sb.AppendLine($"function {request.Name}(items) {{");
            sb.AppendLine("  // TODO: implement the actual logic");
            sb.AppendLine("  return items.map((item) => item);");
            sb.AppendLine("}");
        }
        sb.AppendLine();
        sb.AppendLine("module.exports = { " + request.Name + " };");
        return new CodeResult
        {
            Source = sb.ToString(),
            Language = "javascript",
            Kind = request.Kind,
            Notes = new[] { "This is a scaffold — replace the TODOs with real logic." }
        };
    }

    private CodeResult GenerateSql(CodeRequest request, string description)
    {
        var table = request.Name.ToLowerInvariant();
        var sb = new StringBuilder();
        sb.AppendLine($"-- Generated by Cognify — query scaffold for: {description}");
        sb.AppendLine($"SELECT id, created_at, *   -- TODO: pick real columns");
        sb.AppendLine($"FROM {table}");
        sb.AppendLine($"WHERE created_at >= CURRENT_DATE - INTERVAL '7 days'");
        sb.AppendLine($"ORDER BY created_at DESC");
        sb.AppendLine($"LIMIT 100;");
        return new CodeResult
        {
            Source = sb.ToString(),
            Language = "sql",
            Kind = CodeRequestKind.Query,
            Notes = new[] { "Adjust the table name, columns and filters to your schema." }
        };
    }

    private static string Identifier(string? suggested, string description, CodeRequestKind kind)
    {
        var source = !string.IsNullOrWhiteSpace(suggested) ? suggested : description;
        var words = source.ToLowerInvariant()
            .Split(new[] { ' ', '_', '-', ',', '.', ';', ':', '!', '?', '"', '\n', '\t' },
                   StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
            .Where(w => w.Length > 1 && !StopWords.Contains(w))
            .Take(3).ToList();

        if (words.Count == 0) words.Add(kind == CodeRequestKind.Query ? "report" : "thing");

        var identifier = string.Concat(words.Select(w => char.ToUpperInvariant(w[0]) + w[1..]));
        if (identifier.Length > 0 && char.IsDigit(identifier[0])) identifier = "G" + identifier;
        return identifier;
    }

    private static readonly HashSet<string> StopWords = new()
    {
        "the", "a", "an", "for", "that", "this", "with", "and", "or", "of", "to",
        "write", "create", "make", "generate", "code", "please", "some", "my", "me"
    };

    /// <summary>Namespace used by generated C# code.</summary>
    public string? Namespace { get; set; }
}
