namespace Cognify.Imaging;

/// <summary>
/// A built-in 5x7 bitmap font: the reference glyphs the OCR engine matches
/// against, and a rasterizer for drawing crisp text onto images ("text
/// images" the mind can read back). Lowercase has its own shapes; the set
/// covers A-Z, a-z, 0-9 and common punctuation.
/// </summary>
public static class GlyphAtlas
{
    private static readonly Dictionary<char, string[]> Glyphs = Build();

    /// <summary>The characters the atlas knows.</summary>
    public static IReadOnlyCollection<char> KnownCharacters => Glyphs.Keys;

    /// <summary>True when the OCR can recognize this character.</summary>
    public static bool Knows(char c) => Glyphs.ContainsKey(char.ToUpperInvariant(c)) ||
                                         Glyphs.ContainsKey(c);

    /// <summary>Gets the 7 rows of 5 columns ('X' = ink) for a character, or null.</summary>
    public static string[]? Pattern(char c) => Glyphs.GetValueOrDefault(c);

    /// <summary>
    /// Measures the pixel size of text rendered at a given scale:
    /// (width, height) including inter-character spacing.
    /// </summary>
    public static (int Width, int Height) Measure(string text, int scale = 3)
    {
        int chars = text.Length;
        return (chars <= 0 ? 0 : chars * 6 * scale - scale, 7 * scale);
    }

    /// <summary>
    /// Renders single-line text onto a white background with a black margin,
    /// at the given scale (1 glyph pixel = scale × scale screen pixels).
    /// Returns the smallest image that fits the text plus the margin.
    /// </summary>
    public static PixelBuffer RenderText(string text, int scale = 3, int margin = 4,
        byte ink = 20, byte paper = 245)
    {
        if (string.IsNullOrEmpty(text))
            return new PixelBuffer(margin * 2 + 1, margin * 2 + 7 * scale);
        var (textWidth, textHeight) = Measure(text, scale);
        var image = new PixelBuffer(textWidth + margin * 2, textHeight + margin * 2);
        for (int i = 0; i < image.Rgb.Length; i += 3)
        {
            image.Rgb[i] = paper;
            image.Rgb[i + 1] = paper;
            image.Rgb[i + 2] = paper;
        }

        int penX = margin;
        foreach (var c in text)
        {
            if (c == ' ') { penX += 6 * scale; continue; }
            var pattern = Glyphs.GetValueOrDefault(c) ?? Glyphs.GetValueOrDefault(char.ToUpperInvariant(c));
            if (pattern is null) { penX += 6 * scale; continue; }
            for (int row = 0; row < 7; row++)
                for (int col = 0; col < 5; col++)
                    if (pattern[row][col] == 'X')
                        for (int dy = 0; dy < scale; dy++)
                            for (int dx = 0; dx < scale; dx++)
                                image.SetPixel(penX + col * scale + dx, margin + row * scale + dy,
                                    ink, ink, ink);
            penX += 6 * scale;
        }
        return image;
    }

