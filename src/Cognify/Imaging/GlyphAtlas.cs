        Add('I', ".###.", "..#..", "..#..", "..#..", "..#..", "..#..", ".###.");
        Add('J', "..###", "...#.", "...#.", "...#.", "...#.", "#..#.", ".##..");
        Add('K', "#...#", "#..#.", "#.#..", "##...", "#.#..", "#..#.", "#...#");
