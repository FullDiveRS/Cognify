namespace Cognify.Core;

/// <summary>
/// The kind of input the mind is receiving. Different kinds are appraised
/// differently by the cognitive modules (e.g. <see cref="Feedback"/> influences learning).
/// </summary>
public enum StimulusKind
{
    /// <summary>Verbal or textual input (a question, statement, command).</summary>
    Text,

    /// <summary>Something that happened in the environment (external event).</summary>
    Event,

    /// <summary>Passive observation picked up by the mind.</summary>
    Observation,

    /// <summary>Feedback about the mind's previous response. Drives reinforcement learning.</summary>
    Feedback,

    /// <summary>An internal stimulus generated by the mind itself (e.g. a drive).</summary>
    Internal,

    /// <summary>Visual input — an image or scene description for the vision module.</summary>
    Image,

    /// <summary>Auditory input — a sound or speech clip for the audio module.</summary>
    Audio,

    /// <summary>Motion input — a video clip for visual/audio analysis.</summary>
    Video
}

/// <summary>
/// A single piece of input perceivable by a <see cref="Mind"/>.
/// Create one via the constructor or the <see cref="Text"/> / <see cref="Event"/> helpers.
/// </summary>
public sealed class Stimulus
{
    /// <summary>Creates a stimulus.</summary>
    /// <param name="content">The raw content (text) of the stimulus.</param>
    /// <param name="kind">The kind of stimulus. Defaults to <see cref="StimulusKind.Text"/>.</param>
    /// <param name="intensity">Salience in the range 0..1. Defaults to 0.5.</param>
    /// <param name="metadata">Optional key/value metadata (e.g. reward = "0.8" for feedback).</param>
    public Stimulus(string content, StimulusKind kind = StimulusKind.Text,
                    double intensity = 0.5, IReadOnlyDictionary<string, string>? metadata = null)
    {
        Content = content ?? throw new ArgumentNullException(nameof(content));
        Kind = kind;
        Intensity = Math.Clamp(intensity, 0.0, 1.0);
        Metadata = metadata ?? new Dictionary<string, string>();
        Timestamp = DateTimeOffset.UtcNow;
    }

    /// <summary>The raw content of the stimulus.</summary>
    public string Content { get; }

    /// <summary>The kind of stimulus.</summary>
    public StimulusKind Kind { get; }

    /// <summary>How salient/strong the stimulus is (0..1).</summary>
    public double Intensity { get; }

    /// <summary>Optional metadata carried alongside the stimulus.</summary>
    public IReadOnlyDictionary<string, string> Metadata { get; }

    /// <summary>When the stimulus was created.</summary>
    public DateTimeOffset Timestamp { get; }

    /// <summary>Helper: create a textual stimulus.</summary>
    public static Stimulus Text(string content, double intensity = 0.5) =>
        new(content, StimulusKind.Text, intensity);

    /// <summary>Helper: create an environmental event stimulus.</summary>
    public static Stimulus Event(string content, double intensity = 0.7) =>
        new(content, StimulusKind.Event, intensity);

    /// <summary>Helper: create a feedback stimulus carrying a reward in -1..1.</summary>
    public static Stimulus Feedback(double reward) =>
        new($"feedback:{reward}", StimulusKind.Feedback, Math.Abs(reward),
            new Dictionary<string, string> { ["reward"] = reward.ToString("G") });

    /// <summary>
    /// Helper: create a visual stimulus. The content should describe what is
    /// visible (e.g. "a red apple on a wooden table") or a label/URL; extra
    /// facts like <c>width</c>, <c>height</c>, <c>format</c> may be passed as metadata.
    /// </summary>
    public static Stimulus Image(string description, double intensity = 0.6,
        IReadOnlyDictionary<string, string>? metadata = null) =>
        new(description, StimulusKind.Image, intensity, metadata);

    /// <summary>
    /// Helper: create an auditory stimulus. The content may be a transcript of
    /// speech or a description of the sound; extra facts like <c>duration</c>
    /// (seconds) and <c>loudness</c> (0..1) may be passed as metadata.
    /// </summary>
    public static Stimulus Audio(string description, double intensity = 0.6,
        IReadOnlyDictionary<string, string>? metadata = null) =>
        new(description, StimulusKind.Audio, intensity, metadata);

    /// <summary>
    /// Helper: create a video stimulus. The content describes the clip;
    /// <c>duration</c> (seconds) may be passed as metadata.
    /// </summary>
    public static Stimulus Video(string description, double intensity = 0.6,
        IReadOnlyDictionary<string, string>? metadata = null) =>
        new(description, StimulusKind.Video, intensity, metadata);
}
